"""Extract a small, auditable knowledge snapshot from frozen real Wiki DOMs.

The parser is deliberately restricted to three crops and two machines. Source
facts are derived from DOM text/layout, not generated by a language model.
"""
from __future__ import annotations
import re
from pathlib import Path
from urllib.parse import unquote, urlparse
from bs4 import BeautifulSoup
from .common import BASE, DATA, dump, file_sha, jsonl, load, now, read_jsonl, sha

SCHEMA = 'stardew-verification/1'
CROPS = ('Parsnip', 'Melon', 'Blueberry')
ALIASES = {'Parsnip':['防风草','欧洲萝卜'],'Melon':['甜瓜','哈密瓜'], 'Blueberry':['蓝莓'],
           'Keg':['小桶','酿酒桶'],'Preserves_Jar':['罐头瓶','罐头机'], 'Wine':['果酒'],
           'Jelly':['果酱'],'Pickles':['腌菜'], 'Quality_Crops_Bundle':['高品质作物收集包','献祭']}


def extract():
    sources={r['page_id']:r for r in read_jsonl(DATA/'source_manifest.jsonl')}
    images=read_jsonl(DATA/'image_manifest.jsonl'); occs=read_jsonl(DATA/'occurrence_manifest.jsonl')
    facts=[]; nodes={}; edges=[]; pages={}; soups={}
    def node(node_id, kind='Item', **meta):
        if node_id not in nodes: nodes[node_id]={'id':node_id,'name':node_id.replace('_',' '),'type':kind,'metadata':meta}
        return node_id
    def edge(src,dst,kind,**meta):
        rid='rel:'+sha((src+'|'+kind+'|'+dst).encode())[:24]
        if not any(r['id']==rid for r in edges):
            edges.append({'id':rid,'source':src,'target':dst,'type':kind,'metadata':meta})
    for page,s in sources.items():
        if file_sha(BASE/s['raw_path'])!=s['sha256']:raise ValueError('Source hash mismatch: '+page)
        pages[page]=load(BASE/s['parsed_path'])
        soups[page]=BeautifulSoup((BASE/s['raw_path']).read_text(encoding='utf-8'),'lxml')
        node('source:'+page,'Source',**s)
    def evidence(page, quote, location):
        if not quote.strip():raise ValueError('Empty evidence')
        # Quote is checked against DOM normalized text, preserving row boundaries in location.
        if re.sub(r'\s+',' ',quote) not in soups[page].get_text(' ',strip=True):
            raise ValueError('Quote absent from source: '+page+' '+location)
        s=sources[page]
        return {'page_id':page,'url':s.get('permanent_url',s['url']),'source_sha256':s['sha256'],
                'raw_path':s['raw_path'],'location':location,'quote':quote,
                'quote_sha256':sha(quote.encode()),'review_status':'assistant_checked; independent_human_pending'}
    def add(subject,pred,value,unit,page,quote,location,**extra):
        fid='fact:'+subject+':'+pred
        f={'id':fid,'subject':subject,'predicate':pred,'value':value,'unit':unit,
           'conditions':{'scope':'frozen_wiki_snapshot','version_status':'unverified',
                         'mode':'verification_only','mods':'unsupported','growth_acceleration':'unsupported'},
           'evidence':[evidence(page,quote,location)],**extra}
        facts.append(f);node(subject);node(fid,'Fact',**f)
        edge(subject,fid,'HAS_FACT');edge(fid,'source:'+page,'SUPPORTED_BY')
        return f
    def info(page,label):
        for row in soups[page].select('#infoboxtable tr'):
            cells=row.find_all(['td','th'],recursive=False)
            if len(cells)==2 and cells[0].get('id')=='infoboxsection' and cells[0].get_text(' ',strip=True).rstrip(': ').strip()==label:
                return cells[1].get_text(' ',strip=True),row.get_text(' ',strip=True)
        raise ValueError('Missing infobox field '+page+':'+label)
    def text_span(page,pattern):
        text=soups[page].get_text(' ',strip=True);m=re.search(pattern,text,re.I)
        if not m:raise ValueError('Missing rule '+page+':'+pattern)
        return m.group(0)
    for crop in CROPS:
        node(crop,'CropSpec',aliases=ALIASES[crop]);seed=crop+'_Seeds'
        node(seed,'Item',aliases=[a+'种子' for a in ALIASES[crop]])
        category_quote=text_span(crop,r'The '+crop+r' is a (fruit|vegetable) crop that grows from')
        category=re.search(r'is a (fruit|vegetable)',category_quote).group(1)
        add(crop,'category',category,'category',crop,category_quote,'intro: crop category')
        target,quote=info(seed,'Crop');assert target.replace(' ','_')==crop
        add(seed,'grows_into',crop,'entity',seed,quote,'#infoboxtable row[Crop]')
        edge(seed,crop,'GROWS_INTO',fact_id='fact:'+seed+':grows_into')
        for pred,label,unit in [('growth_days','Growth Time','growth_nights'),('season','Season','season')]:
            v,q=info(crop,label);v=int(re.search(r'\d+',v).group()) if pred=='growth_days' else v
            add(crop,pred,v,unit,crop,q,'#infoboxtable row['+label+']')
            if pred=='season':
                node(v,'Season');edge(crop,v,'GROWS_IN_SEASON',fact_id='fact:'+crop+':season')
        v,q=info(seed,'General Store');price=int(re.findall(r'([\d,]+)g',v)[-1].replace(',',''))
        add(seed,'buy_price',price,'g',seed,q,'#infoboxtable row[General Store]',shop='Pierre')
        price_table=pages[crop]['tables'][3]
        prices=[int(re.search(r'(\d+)g',r[-1]).group(1)) for r in price_table['rows'] if r and re.search(r'(\d+)g',r[-1])]
        assert len(prices)==4
        for quality,value in zip(['normal','silver','gold','iridium'],prices):
            add(crop,'sell_'+quality,value,'g',crop,price_table['text'],'table[3] (zero-based): Base sell prices',quality=quality,profession='none')
        stages=next(t for t in pages[crop]['tables'] if t['rows'] and t['rows'][0][0]=='Stage 1')
        durations=[int(re.match(r'(\d+)',c).group()) for c in stages['rows'][-1] if re.match(r'\d+',c)]
        assert sum(durations)==next(f['value'] for f in facts if f['id']=='fact:'+crop+':growth_days')
        add(crop,'stage_durations',durations,'growth_nights',crop,stages['text'],f"table[{stages['table_index']}]: header + durations")
        for i,duration in enumerate(durations+[0],1):
            stage=crop+'_Stage_'+str(i);node(stage,'CropStage',crop=crop,stage=i)
            edge(crop,stage,'HAS_STAGE',order=i)
            add(stage,'duration',duration,'growth_nights',crop,stages['text'],f"table[{stages['table_index']}]: column[{i-1}]")
            if i>1:edge(crop+'_Stage_'+str(i-1),stage,'NEXT_STAGE')
        if crop=='Blueberry':
            q=text_span(crop,r'Each harvest yields 3 Blueberries, with a 2% chance of more blueberries\.')
            add(crop,'base_yield',int(re.search(r'yields (\d+)',q).group(1)),'items_per_harvest',crop,q,'intro: harvest yield')
            reg=int(re.search(r'Regrowth: (\d+)',stages['text']).group(1))
            add(crop,'regrowth',reg,'growth_nights',crop,stages['text'],f"table[{stages['table_index']}]: After-Harvest")
            node(crop+'_Stage_7','CropStage',crop=crop,stage=7,phase='regrowth')
    q=text_span('Crops',r'when seasons change \(after the (\d+)th day\), the crop will wither and die\.')
    add('Calendar','season_days',int(re.search(r'(\d+)',q).group()),'days','Crops',q,'intro: seasonal boundary')
    q=text_span('Crops',r'If a seed is planted into unwatered soil.*?The grow times on this page assume the seeds are watered the day they are planted\.')
    add('Calendar','watered_growth',True,'condition','Crops',q,'Growth: watering')
    for machine,products in [('Keg',['Wine']),('Preserves_Jar',['Jelly','Pickles'])]:
        node(machine,'EquipmentType',aliases=ALIASES[machine])
        v,q=info(machine,'Ingredients')
        materials={name.strip().replace(' ','_'):int(n) for name,n in re.findall(r'([A-Za-z ]+) \((\d+)\)',v)}
        add(machine,'materials',materials,'items',machine,q,'#infoboxtable row[Ingredients]')
        v,q=info(machine,'Recipe Source');add(machine,'farming_level',int(re.search(r'Level (\d+)',v).group(1)),'level',machine,q,'#infoboxtable row[Recipe Source]')
        for prod in products:
            row=next(r for r in pages[machine]['tables'][1]['rows'] if len(r)>5 and r[1]==prod)
            q=' '.join(row);mins=int(re.search(r'(\d+)',row[4]).group(1))
            multiplier=int(re.search(r'(\d+) ×',row[5]).group(1));offset=int(re.search(r'\+ (\d+)',row[5]).group(1)) if '+' in row[5] else 0
            add(prod,'processing_minutes',mins,'machine_minutes',machine,q,'table[1]: '+prod)
            add(prod,'value_formula',{'multiplier':multiplier,'offset':offset},'g',machine,q,'table[1]: '+prod,ingredient_quality='ignored',profession='none')
            add(prod,'equipment',machine,'entity',machine,q,'table[1]: '+prod)
            edge(prod,machine,'PRODUCED_BY',fact_id='fact:'+prod+':equipment')
            for crop in CROPS:
                category=next(f['value'] for f in facts if f['id']=='fact:'+crop+':category')
                if (prod in ['Wine','Jelly'] and category=='fruit') or (prod=='Pickles' and category=='vegetable'):
                    edge(crop,prod,'CAN_PROCESS',fact_id='fact:'+prod+':value_formula',
                         support_fact_ids=['fact:'+crop+':category','fact:'+prod+':value_formula'],derivation='crop category plus machine input rule')
    q=text_span('Keg',r'One full day is (\d+) minutes, where day is (\d+) minutes and night is (\d+) minutes\.')
    add('Calendar','machine_day',int(re.search(r'is (\d+)',q).group(1)),'machine_minutes','Keg',q,'Products: machine clock')
    # Independent redundant source for the same jar formula.
    q=text_span('Jellies_and_Pickles',r'The value of a single jar.*?unaffected by the quality of the fruit or vegetable used\.')
    for prod in ['Jelly','Pickles']:
        f=next(f for f in facts if f['id']=='fact:'+prod+':value_formula')
        f['evidence'].append(evidence('Jellies_and_Pickles',q,'intro: value formula'))
        edge(f['id'],'source:Jellies_and_Pickles','SUPPORTED_BY')
    table=soups['Bundles'].find(id='Quality_Crops_Bundle').find_parent('table')
    count=len([img for img in table.select('img') if img.get('src','').endswith('/Bundle_Slot.png')])
    add('Quality_Crops_Bundle','choose_k',count,'requirements','Bundles',table.get_text(' ',strip=True),'table #Quality_Crops_Bundle; count img[src$="/Bundle_Slot.png"]',alignment_origin='html_layout')
    requirements=[]
    for row in table.find_all('tr'):
        cells=row.find_all('td',recursive=False)
        if cells and 'Gold quality' in cells[-1].get_text():
            q=row.get_text(' ',strip=True);m=re.search(r'(Parsnip|Melon|Pumpkin|Corn) \((\d+)\)',q)
            if m:
                requirements.append({'item':m[1],'quantity':int(m[2]),'quality':'gold'})
                add(m[1],'quality_bundle',{'quantity':int(m[2]),'quality':'gold'},'items','Bundles',q,'Quality_Crops_Bundle row '+m[1])
                node('Quality_Crops_Bundle','Rule');edge(m[1],'Quality_Crops_Bundle','BUNDLE_REQUIREMENT')
    assert len(requirements)==4 and count==3
    add('Quality_Crops_Bundle','requirements',requirements,'requirements','Bundles',table.get_text(' ',strip=True),'#Quality_Crops_Bundle parent table')
    # Each occurrence has its own location; matching file names is alignment, not visual inference.
    for o in occs:o['selector']='.mw-parser-output img'
    jsonl(DATA/'occurrence_manifest.jsonl',occs)
    gallery=[]
    for im in images:
        if file_sha(BASE/im['path'])!=im['sha256']:raise ValueError('Image hash mismatch')
        filename=Path(unquote(urlparse(im['url']).path)).name
        subject=filename.rsplit('.',1)[0];node(subject,'CropStage' if '_Stage_' in subject else 'Item')
        matched=[o for o in occs if Path(unquote(urlparse(o['asset_url']).path)).name==filename or Path(unquote(urlparse(o['asset_url']).path)).name.endswith('px-'+filename)]
        selected=[]
        for o in matched:
            node(o['occurrence_id'],'VisualOccurrence',**o);edge(subject,o['occurrence_id'],'DEPICTED_AT');edge(o['occurrence_id'],'source:'+o['page_id'],'OCCURS_IN')
            selected.append(o['occurrence_id'])
        gallery.append({**im,'entity':subject,'occurrence_ids':selected,'alignment_origin':'html_layout',
                        'identity_status':'ambiguous_product_color' if subject in ['Pink_Wine','Pink_Jelly'] else 'assistant_checked'})
    jsonl(DATA/'facts.jsonl',facts);jsonl(DATA/'gallery.jsonl',gallery)
    graph={'entities':list(nodes.values()),'relationships':edges}
    dump(DATA/'graph_input.json',graph)
    snapshot=sha((file_sha(DATA/'facts.jsonl')+file_sha(DATA/'gallery.jsonl')+file_sha(DATA/'source_manifest.jsonl')).encode())
    manifest={'schema':SCHEMA,'snapshot_id':snapshot,'at':now(),'facts':len(facts),'nodes':len(nodes),'edges':len(edges),
              'source_sha256':file_sha(DATA/'source_manifest.jsonl'),'facts_sha256':file_sha(DATA/'facts.jsonl'),
              'gallery_sha256':file_sha(DATA/'gallery.jsonl'),'graph_input_sha256':file_sha(DATA/'graph_input.json'),
              'scope':'verification_only; frozen Wiki revisions; exact game version unverified'}
    dump(DATA/'knowledge_manifest.json',manifest)
    dump(BASE/'results/v01.json',{'status':'PARTIAL','pages':len(sources),'images':len(images),'occurrences':len(occs),
        'aligned_occurrences':sum(len(g['occurrence_ids']) for g in gallery),'facts':len(facts),
        'technical_checks_passed':True,'blockers':['Exact game version unverified','Independent human fact review pending','Asset redistribution licenses not cleared'],
        'acquisition':'normal browser DOM/pageAssets; automated HTTP route stopped at 403','snapshot_id':snapshot})
    print(manifest)
    return manifest

if __name__=='__main__':extract()
